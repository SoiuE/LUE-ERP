CREATE TABLE suppliers (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  supplier_code VARCHAR(64) NOT NULL,
  supplier_name VARCHAR(160) NOT NULL,
  contact_name VARCHAR(100),
  phone VARCHAR(40),
  email VARCHAR(160),
  address VARCHAR(500),
  note VARCHAR(1000),
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_suppliers_code (supplier_code),
  INDEX idx_suppliers_status_deleted (status,is_deleted)
);

CREATE TABLE shops (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  shop_name VARCHAR(160) NOT NULL,
  platform VARCHAR(32) NOT NULL DEFAULT 'ALIEXPRESS',
  shop_identifier VARCHAR(160) NOT NULL,
  account_entity VARCHAR(160),
  owner_name VARCHAR(100),
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  note VARCHAR(1000),
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_shops_platform_identifier (platform,shop_identifier),
  INDEX idx_shops_status_deleted (status,is_deleted)
);

CREATE TABLE package_materials (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  material_code VARCHAR(64) NOT NULL,
  material_name VARCHAR(160) NOT NULL,
  category ENUM('PRODUCT_PACKAGING','SHIPPING_MATERIAL') NOT NULL,
  specification VARCHAR(255),
  unit VARCHAR(32) NOT NULL,
  unit_price DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
  safety_stock DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  note VARCHAR(1000),
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_package_materials_code (material_code),
  INDEX idx_package_materials_category_status (category,status,is_deleted)
);

CREATE TABLE skus (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  internal_sku VARCHAR(100) NOT NULL,
  spu VARCHAR(100),
  product_name VARCHAR(255) NOT NULL,
  name_zh VARCHAR(255),
  name_en VARCHAR(255),
  specification VARCHAR(255),
  color VARCHAR(100),
  size VARCHAR(100),
  barcode VARCHAR(100),
  category VARCHAR(160),
  supplier_id BIGINT NULL,
  purchase_price DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
  supply_price DECIMAL(18,4) NOT NULL DEFAULT 0.0000,
  weight DECIMAL(18,4),
  length DECIMAL(18,4),
  width DECIMAL(18,4),
  height DECIMAL(18,4),
  default_product_packaging_plan JSON NULL,
  default_shipping_material_plan JSON NULL,
  image_url VARCHAR(1000),
  status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  note VARCHAR(1000),
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_skus_internal_sku (internal_sku),
  INDEX idx_skus_spu (spu),
  INDEX idx_skus_barcode (barcode),
  INDEX idx_skus_status_deleted (status,is_deleted),
  CONSTRAINT fk_skus_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
);
