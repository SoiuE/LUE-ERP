CREATE TABLE order_summaries (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  import_batch_id BIGINT NOT NULL,
  shop_id BIGINT NOT NULL,
  platform_order_no VARCHAR(160) NULL,
  platform_sku VARCHAR(160) NOT NULL,
  sku_id BIGINT NULL,
  order_mode ENUM('JIT','WAREHOUSE') NOT NULL,
  quantity DECIMAL(18,4) NOT NULL DEFAULT 0,
  sales_amount DECIMAL(18,4) NOT NULL DEFAULT 0,
  refund_amount DECIMAL(18,4) NOT NULL DEFAULT 0,
  platform_fee DECIMAL(18,4) NOT NULL DEFAULT 0,
  order_date DATE NOT NULL,
  business_key CHAR(64) NOT NULL,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_order_summaries_business (shop_id,business_key),
  INDEX idx_order_summaries_filter (shop_id,order_mode,order_date),
  INDEX idx_order_summaries_sku (sku_id,order_date),
  CONSTRAINT fk_order_summaries_batch FOREIGN KEY (import_batch_id) REFERENCES import_batches(id),
  CONSTRAINT fk_order_summaries_shop FOREIGN KEY (shop_id) REFERENCES shops(id),
  CONSTRAINT fk_order_summaries_sku FOREIGN KEY (sku_id) REFERENCES skus(id)
);

CREATE TABLE exceptions (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  exception_no VARCHAR(32) NOT NULL,
  exception_type VARCHAR(40) NOT NULL,
  status ENUM('OPEN','RESOLVED','CLOSED') NOT NULL DEFAULT 'OPEN',
  shop_id BIGINT NULL,
  platform_sku VARCHAR(160) NULL,
  order_summary_id BIGINT NULL,
  raw_data JSON NULL,
  title VARCHAR(255) NOT NULL,
  resolution_note VARCHAR(1000) NULL,
  resolved_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_exceptions_status_type (status,exception_type,created_at),
  INDEX idx_exceptions_shop_sku (shop_id,platform_sku,status),
  CONSTRAINT fk_exceptions_shop FOREIGN KEY (shop_id) REFERENCES shops(id),
  CONSTRAINT fk_exceptions_order FOREIGN KEY (order_summary_id) REFERENCES order_summaries(id)
);
